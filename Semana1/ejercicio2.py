# PEDIR UN NUMERO DE PUERTO E IMPRIMIR SI ES SSH, HTTP, HTTPS U OTRO

print ("¿QUÉ PUERTO ESTÁS USANDO?")
puerto = (int(input ("INGRESA EL NUMERO DE PUERTO QUE TIENES: ")))

if puerto == 22:
    print("ESTÁS USANDO SSH")
elif puerto == 80:
    print("ESTÁS USANDO HTTP")
elif puerto == 443:
    print("ESTÁS USANDO HTTPS")
else: 
    print("ESTÁS USANDO UN PUERTO DIFERENTE A HTTP, HTTPS, SSH")